// Token Radar — the value model ("radar-2").
//
// One sealed snapshot in, one ranked board out. The board ranks only protocols
// that record no token and are not a wrapped, staked or bridged product of a
// token that already trades (see isRankable: the house watchlist's own rule,
// applied to every candidate). Protocols whose token already trades are kept
// apart in the live set and shown at their market value, never ranked.
//
// impliedValue(protocol) uses only the snapshot's own figures:
//
//   base      = tvl_usd x 0.20
//   category  = a multiple by the protocol's category (see CATEGORY_MULTIPLE)
//   growth    = 1 + 0.6 x clamp(change_7d, -50, 150) / 100
//   maturity  = 0.80 + 0.40 x min(age_days, 1460) / 1460   (unknown age: 365)
//   breadth   = 1 + 0.025 x min(chains - 1, 12)
//   implied   = round(base x category x growth x maturity x breadth), at least $1
//
// Why these factors: TVL is the size of the business a token would capture a
// share of; the category multiple says how much of that business each kind of
// protocol keeps (lending and derivatives monetise flows, bridges mostly pass
// value through); seven-day growth rewards momentum and punishes shrinkage;
// maturity rewards protocols that have run a long time with no token yet (the
// launch, if it ever comes, prices years of pent-up use); breadth rewards
// protocols live on many chains, where a launch reaches more users. No
// protocol name is ever special-cased: the same function scores every row.

/** One protocol of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.2,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.8,
  maturity_range: 0.4,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_per_chain: 0.025,
  breadth_max_chains: 12,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the dashboard's reference table carries. */
export const LIVE_ROWS = 24;

/**
 * What a token is worth per dollar of TVL, by what the protocol does. Lending
 * and derivatives keep the most of the flow they touch, so they price highest;
 * bridges mostly pass value through, so they price lowest. The table is keyed
 * by category, never by name, and applies to every protocol in that category.
 */
const CATEGORY_MULTIPLE: Array<[RegExp, number]> = [
  [/lend/i, 1.2],
  [/cdp/i, 1.2],
  [/derivative/i, 1.15],
  [/perpetual/i, 1.15],
  [/yield/i, 1.1],
  [/rwa/i, 1.1],
  [/dex/i, 1.05],
  [/risk curator/i, 1.05],
  [/capital allocator/i, 1.05],
  [/restak/i, 1.05],
  [/prediction/i, 1.0],
  [/bridge/i, 0.85],
  [/liquid staking/i, 0.9],
  [/cex/i, 0.8],
];

/** A protocol's category multiple: the first matching row, else 1. */
export function categoryMultiple(category: string | null): number {
  const c = category ?? '';
  for (const [re, mult] of CATEGORY_MULTIPLE) if (re.test(c)) return mult;
  return 1;
}

